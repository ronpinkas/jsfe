import assert from 'node:assert/strict';
import {pickProviderQuestion,readFormAnswer} from '../dist/helpers/index.js';
import {setTaskGate} from '../dist/forms/identity-flows.js';
import {beginProviderRequest,finishProviderRequest,takeReadyProviderRequests} from '../dist/forms/flows.js';
let checks=0;const equal=(a,b)=>{assert.deepEqual(a,b);checks++;};
const cargo={forms:{task:{id:'task',task:'task'},child:{id:'child',task:'task'},other:{id:'other',task:'other'}}};
const a={subject:'account',facts:[{key:'balance'},{key:'due'}]},b={subject:'other source',facts:[{key:'status'}]};
equal(beginProviderRequest(cargo,'child',a,['balance'],{id:1}),{owner:'task',queued:false});
equal(beginProviderRequest(cargo,'child',a,['balance','due'],null),{owner:'task',queued:true});
equal(cargo.forms.task.providerRequests[0].keys,['balance','due']);
equal(beginProviderRequest(cargo,'child',b,['status'],null),{owner:'task',queued:true});
equal(beginProviderRequest(cargo,'other',a,['balance'],null),{owner:'other',queued:false});
const result=finishProviderRequest(cargo,'task',a,['balance']);
equal(result.keys,['balance','due']);equal(result.remaining.map(r=>r.provides),[b]);
equal(cargo.forms.task.providerRequests,undefined);equal(cargo.forms.other.providerRequests.length,1);
equal(finishProviderRequest(cargo,'task',a,['balance']),{keys:['balance'],remaining:[]});
equal(beginProviderRequest(cargo,'absent',a,['balance'],null),{owner:'',queued:false});
const privateCatalog={...a,gate:{flow:'verify',verified:['cargo.trusted']}};
equal(setTaskGate(cargo,'child','verify',true),true);
equal(beginProviderRequest(cargo,'child',privateCatalog,['balance'],null),{owner:'task',queued:true});
equal(takeReadyProviderRequests(cargo,'child'),[]);
cargo.trusted=true;equal(takeReadyProviderRequests(cargo,'child').map(r=>r.keys),[['balance']]);
equal(setTaskGate(cargo,'child','verify',false),true);equal(cargo.forms.task.activeGates,undefined);
cargo.trusted=false;setTaskGate(cargo,'child','verify',true);beginProviderRequest(cargo,'child',privateCatalog,['due'],null);setTaskGate(cargo,'child','verify',false);
equal(takeReadyProviderRequests(cargo,'child').map(r=>r.keys),[['due']]);
cargo.trusted=true;beginProviderRequest(cargo,'child',privateCatalog,['balance'],null);equal(takeReadyProviderRequests(cargo,'child'),[]);
finishProviderRequest(cargo,'task',privateCatalog,['balance']);equal(cargo.forms.task.providerGateActive,undefined);
equal(setTaskGate(cargo,'absent','verify',true),false);
const questions=[{key:'balance',words:['balance','saldo','total balance']},{key:'statement',words:['statement balance','saldo de mi estado de cuenta']},{key:'available',words:['available credit','crédito disponible']}];
equal(pickProviderQuestion("what's my statement balance?",questions),'statement');
equal(pickProviderQuestion('¿cuál es el saldo de mi estado de cuenta?',questions),'statement');
equal(pickProviderQuestion('what is my balance?',questions),'balance');
equal(pickProviderQuestion('not my statement balance',questions),'');
equal(pickProviderQuestion('available credit please',questions),'available');
equal(pickProviderQuestion('yes',questions),'');
equal(readFormAnswer("what's my statement balance?",[],{},'',questions).questions,['statement']);
console.log(`provider request queue: all checks passed (${checks})`);
