import assert from 'node:assert/strict';
import { openFormInstance,acceptFormReadings } from '../dist/helpers/form-state.js';
import { prepareFormAction,beginFormAction,finishFormAction,confirmFormRevision,formSignature } from '../dist/helpers/form-actions.js';
let checks=0;const eq=(a,b,label)=>{assert.deepEqual(a,b,label);checks++;};
const cargo={account:'A',verified:true};
const id=openFormInstance(cargo,'pay',[{name:'amount',profile:{kind:'amount'}}]);
acceptFormReadings(cargo,[{form:id,name:'amount',value:'40',ok:true}]);
const action={action:'pay',subject:'cargo.account',gate:{verified:'cargo.verified'},confirm:{exact:true},outcomes:{paid:'resolved',unknown:'unresolved'}};
let record=prepareFormAction(cargo,id,action,{amount:40,account:'A'});
eq(beginFormAction(cargo,id,action,record),false,'exact action cannot run without confirmation');
confirmFormRevision(cargo,id);
eq(beginFormAction(cargo,id,action,record),true,'confirmed current request can be attempted');
const restored=JSON.parse(JSON.stringify(cargo));
const resumed=prepareFormAction(restored,id,action,{account:'A',amount:40});
eq(resumed.key,record.key,'reentry retains the same request key across serialization');
eq(beginFormAction(restored,id,action,resumed),false,'an attempted request is never blindly repeated');
finishFormAction(restored,id,action,{status:'paid',reference:'receipt'});
eq(beginFormAction(restored,id,action,resumed),false,'completed request is never executed again');
acceptFormReadings(restored,[{form:id,name:'amount',value:'50',ok:true}]);
const changed=prepareFormAction(restored,id,action,{account:'A',amount:50});
eq(changed.key!==record.key,true,'a new accepted request gets a distinct key');
eq(beginFormAction(restored,id,action,changed),false,'correction invalidates confirmation');
confirmFormRevision(restored,id);restored.verified=false;
eq(beginFormAction(restored,id,action,changed),false,'expired gate blocks execution');
restored.verified=true;restored.account='B';
eq(beginFormAction(restored,id,action,changed),false,'changed subject blocks previously prepared request');
restored.account='A';
eq(beginFormAction(restored,id,action,changed),true,'unchanged subject and current confirmation allow execution');
finishFormAction(restored,id,action,null);
eq(changed.status,'unknown','missing result fails to unknown rather than claiming success');
const held=prepareFormAction(restored,id,action,{account:'A',amount:60});
eq(held.key,changed.key,'unknown outcome requires reconciliation before a new request replaces it');
eq(beginFormAction(restored,id,action,held),false,'unknown outcome is not retried');
eq(formSignature({b:2,a:{d:4,c:3}}),formSignature({a:{c:3,d:4},b:2}),'request identity ignores object property order');
restored.account='B';
const separate=prepareFormAction(restored,id,action,{account:'B',amount:60});
eq(separate.key!==held.key,true,'an unresolved action does not capture a different subject in the same owner');
eq(restored.actionJournal[held.key].status,'unknown','changing the subject retains the original unresolved hold');
console.log(`form-actions: ${checks} checks passed`);
